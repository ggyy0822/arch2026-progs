#!/usr/bin/env python3
"""Generate the exact set of 2,644 distance-11 states, without solutions.

The CSV is the complete distance-11 set from the HW1 exhaustive host BFS.
Only the 22-bit combined rank is stored; target search still finds the path.
"""
import csv
from pathlib import Path

source = Path(__file__).with_name('rubik_distance11.csv')
with source.open(newline='') as stream:
    rows = list(csv.DictReader(stream))
assert len(rows) == 2644
assert all(int(row['expected_length']) == 11 for row in rows)
keys = sorted(int(row['rank']) for row in rows)
assert len(set(keys)) == len(keys)
assert keys[0] >= 0 and keys[-1] < 3674160
print('# Generated by tools/generate_rubik_hard11.py; do not edit by hand.')
print('.section .rodata')
print('.globl hard11_table')
print('hard11_table:')
for key in keys:
    print('    .byte ' + ','.join(str((key >> (8 * i)) & 255) for i in range(3)))
