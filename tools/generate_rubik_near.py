#!/usr/bin/env python3
"""Build exact distance <=5 meet-in-the-middle entries from HW1 transitions.

Run: python3 tools/generate_rubik_near.py > src/rubik/near.S
Each five-byte entry stores the low 16 bits of a combined state index and
a 23-bit solution code. A bucket index supplies the high bits.
"""
from pathlib import Path
import re

SOURCE = Path(__file__).resolve().parents[1] / 'src/rubik/tables.S'
text = SOURCE.read_text()

def table(label):
    match = re.search(r'^' + label + r':(.*?)(?=^\.globl |\Z)', text,
                      re.MULTILINE | re.DOTALL)
    if match is None:
        raise ValueError(label)
    return [int(v) for line in match.group(1).splitlines()
            if line.strip().startswith(('.half', '.byte'))
            for v in re.findall(r'\d+', line)]

perms = table('rt_perm')
orients = table('rt_orient')
perms = [perms[i * 5040:(i + 1) * 5040] for i in range(3)]
orients = [orients[i * 729:(i + 1) * 729] for i in range(3)]

def turn(state, move):
    p, o = state
    face = move // 3
    for _ in range(move % 3 + 1):
        p, o = perms[face][p], orients[face][o]
    return p, o

paths = {(0, 0): ()}
frontier = [(0, 0)]
for depth in range(1, 6):
    next_frontier = []
    for state in frontier:
        for move in range(9):
            child = turn(state, move)
            if child not in paths:
                reverse = (move // 3) * 3 + 2 - (move % 3)
                paths[child] = (reverse,) + paths[state]
                next_frontier.append(child)
    frontier = next_frontier

print('# Generated by tools/generate_rubik_near.py; do not edit by hand.')
print('.section .rodata')
print('.balign 2')
print('.globl near_bucket')
print('near_bucket:')
ordered = sorted(paths.items(), key=lambda item: item[0][0] * 729 + item[0][1])
keys = [p * 729 + o for (p, o), _ in ordered]
pos = 0
for high in range(58):
    while pos < len(keys) and (keys[pos] >> 16) < high:
        pos += 1
    print('    .half ' + str(pos))
print('.globl near_table')
print('near_table:')
for ((p, o), path), key in zip(ordered, keys):
    code = len(path)
    for i, move in enumerate(path):
        code |= move << (3 + 4 * i)
    values = [(key >> (8 * j)) & 255 for j in range(2)]
    values += [(code >> (8 * j)) & 255 for j in range(3)]
    print('    .byte ' + ','.join(map(str, values)))
