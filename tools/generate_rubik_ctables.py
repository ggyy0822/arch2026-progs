#!/usr/bin/env python3
"""Convert HW1's integer transition data to a self-contained C object.

Run: python3 tools/generate_rubik_ctables.py > src/rubik/tables.c
"""
from pathlib import Path
import re

source = Path(__file__).resolve().parents[1] / 'src/rubik/tables.S'
text = source.read_text()

def values(label):
    match = re.search(r'^' + label + r':(.*?)(?=^\.globl |\Z)', text,
                      re.MULTILINE | re.DOTALL)
    if match is None:
        raise ValueError(label)
    return [int(v) for line in match.group(1).splitlines()
            if line.strip().startswith(('.half', '.byte'))
            for v in re.findall(r'\d+', line)]

print('/* Generated by tools/generate_rubik_ctables.py. */')
print('#include <stdint.h>')
for old, new, ctype, extent in [
    ('rt_perm', 'c_perm', 'uint16_t', '[15120]'),
    ('rt_orient', 'c_orient', 'uint16_t', '[2187]'),
    ('rt_pd', 'c_pd', 'uint8_t', '[5040]'),
    ('rt_od', 'c_od', 'uint8_t', '[729]'),
]:
    entries = values(old)
    print(f'const {ctype} {new}{extent} = {{')
    for index in range(0, len(entries), 16):
        print('    ' + ', '.join(map(str, entries[index:index + 16])) + ',')
    print('};')
